export function projectBySlug(slug: string): Project | undefined {
  return projects.find((p) => p.slug === slug)
}

export function featuredProjects(): Project[] {
  return projects.filter((p) => p.featured)
}

export function relatedProjects(project: Project, limit = 3): Project[] {
  return projects
    .filter((p) => p.slug !== project.slug)
    .map((p) => {
      let score = 0
      if (p.category === project.category) score += 3
      score += p.categories.filter((c) => project.categories.includes(c)).length
      if (p.university === project.university) score += 1
      score += p.technologies.filter((t) => project.technologies.includes(t)).length
      return { p, score }
    })
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((x) => x.p)
}

export function projectsByCategory(slug: string): Project[] {
  return projects.filter((p) => p.categories.includes(slug))
}

export function countByCategory(slug: string): number {
  return projectsByCategory(slug).length
}
